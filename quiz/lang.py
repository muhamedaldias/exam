def get_lang(request):
    """Return 'ar' or 'en' from session (default English = current behavior)."""
    code = request.session.get("lang", "en")
    return code if code in STRINGS else "en"


def t(request, key, **kwargs):
    """Translate a key for this request's language."""
    text = STRINGS[get_lang(request)].get(key, STRINGS["en"].get(key, key))
    return text.format(**kwargs) if kwargs else text
